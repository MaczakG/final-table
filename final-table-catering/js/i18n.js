const FT_LANG_KEY = "ft-lang";

function ftGetLang() {
  const stored = localStorage.getItem(FT_LANG_KEY);
  if (stored === "hu" || stored === "en") return stored;
  return "hu";
}

function ftSetLang(lang) {
  localStorage.setItem(FT_LANG_KEY, lang);
}

function ftResolve(path, lang) {
  const parts = path.split(".");
  let node = I18N[lang];
  for (const part of parts) {
    if (node == null) return undefined;
    node = node[part];
  }
  return node;
}

function ftTranslate(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = ftResolve(key, lang);
    if (typeof value === "string") {
      el.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-list]").forEach((el) => {
    const key = el.getAttribute("data-i18n-list");
    const value = ftResolve(key, lang);
    if (Array.isArray(value)) {
      el.innerHTML = "";
      value.forEach((item) => {
        const li = document.createElement("li");
        li.textContent = item;
        el.appendChild(li);
      });
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    const value = ftResolve(key, lang);
    if (typeof value === "string") {
      el.alt = value;
    }
  });

  const titleKey = document.documentElement.getAttribute("data-i18n-title");
  if (titleKey) {
    const value = ftResolve(titleKey, lang);
    if (typeof value === "string") document.title = value;
  }

  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.getAttribute("data-lang-btn") === lang ? "true" : "false");
  });
}

function ftApplyLang(lang) {
  ftSetLang(lang);
  ftTranslate(lang);
}

document.addEventListener("DOMContentLoaded", () => {
  ftTranslate(ftGetLang());
});
